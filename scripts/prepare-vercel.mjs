function isCodeFile(relativePath) {
  return CODE_EXTENSIONS.has(extname(relativePath));
}

// Files that must stay in api/ after staging. Every non-underscore code file
// under api/ becomes a Vercel function, so the single generated index.ts must
// be the only such file left behind. Underscore helpers stay because
// server/_shared modules import them through ../../api/_x.js paths (and they
// are never deployed as functions); test files stay and are removed from the
// deployment by .vercelignore.
function staysInApi(relativePath) {
  const fileName = basename(relativePath);
  if (fileName.startsWith('_')) return true;
  if (/\.(test|spec)\./.test(relativePath)) return true;
  if (!isCodeFile(relativePath)) return true;
  // api/mcp.ts must stay a real function: vercel.json rewrites /mcp and
  // /.well-known/mcp -> /api/mcp, which resolve to the function directly
  // (rewrite destinations are not re-routed through the /api/(.*) rewrite).
  // It is also a material source for the /mcp URL in build:sitemap's static
  // manifest, so removing it fails build:sitemap.
  if (relativePath === 'mcp.ts') return true;
  // The api/mcp/ implementation tree moves into .vercel-api-routes/mcp/ so
  // Vercel doesn't count every nested .ts file as a separate function (the
  // free plan is limited to 12). api/mcp.ts imports are rewritten to point
  // at the staged tree and generate-public-product-facts.mjs is patched to
  // dynamically import from .vercel-api-routes/ instead.
  return false;
}

function routePathFromFile(relativePath) {
  const extension = extname(relativePath);
  const withoutExtension = relativePath.slice(0, -extension.length);
  const parts = withoutExtension.split(sep);
  const fileName = parts.at(-1) ?? '';

  if (
    !['.js', '.ts'].includes(extension) ||
    fileName.startsWith('_') ||
    fileName.endsWith('.test') ||
    relativePath.startsWith('mcp/') ||
    relativePath === 'not-found.ts'
  ) {
    return null;
  }

  const routeParts = parts.map((part) => {
    if (part.startsWith('[...') && part.endsWith(']')) return '*';
    if (part.startsWith('[') && part.endsWith(']')) return `:${part.slice(1, -1)}`;
    return part;
  });
  return `/${routeParts.join('/')}`;
}

async function collectFiles(directory, prefix = '') {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const relativePath = prefix ? join(prefix, entry.name) : entry.name;
    if (entry.isDirectory()) {
      files.push(...(await collectFiles(join(directory, entry.name), relativePath)));
    } else {
      files.push(relativePath);
    }
  }
  return files;
}

function sortRoutes(routes) {
  return routes.sort((left, right) => {
    const leftDynamic = left.routePath.includes(':') || left.routePath.includes('*');
    const rightDynamic = right.routePath.includes(':') || right.routePath.includes('*');
    if (leftDynamic !== rightDynamic) return leftDynamic ? 1 : -1;
    if (left.routePath.includes('*') !== right.routePath.includes('*')) {
      return left.routePath.includes('*') ? 1 : -1;
    }
    return right.routePath.length - left.routePath.length;
  });
}

function renderIndex(routes) {
  const loaders = routes
    .map(({ routePath, relativePath }) => {
      const modulePath = relativePath.slice(0, -extname(relativePath).length).split(sep).join('/');
      return `  ${JSON.stringify(routePath)}: () => import('../.vercel-api-routes/${modulePath}'),`;
    })
    .join('\n');

  const nodeStyleRoutes = JSON.stringify(['/story', '/og-story']);

  return `// @ts-nocheck
/* AUTO-GENERATED by scripts/prepare-vercel.mjs. Do not edit. */
// Vercel sees this file as the only API function. The source route modules are
// staged in .vercel-api-routes/ (same depth as api/, so relative imports of
// ../server/... keep resolving) and loaded through this generated static
// import map.

const routeLoaders = {
${loaders}
};
const nodeStyleRoutes = new Set(${nodeStyleRoutes});
const routePatterns = Object.entries(routeLoaders).map(([pattern, load]) => ({ pattern, load }));

function requestUrl(req) {
  const host = req.headers?.host || 'localhost';
  const protocol = req.headers?.['x-forwarded-proto'] || 'https';
  const rawUrl = req.url || '/';
  const url = new URL(rawUrl, protocol + '://' + host);
  const stagedRoute = url.searchParams.get('__wm_route');

  // The rewrite carries the original route explicitly. The header fallbacks
  // cover Vercel preview invocations and direct calls to /api/index.
  if (stagedRoute !== null) {
    url.searchParams.delete('__wm_route');
    url.pathname = '/api/' + stagedRoute.replace(/^\\/+/, '');
  } else if (url.pathname === '/api/index' || url.pathname === '/api/index.ts') {
    const originalPath = req.headers?.['x-matched-path'] || req.headers?.['x-original-url'];
    if (typeof originalPath === 'string' && originalPath.startsWith('/api/')) {
      const original = new URL(originalPath, url);
      url.pathname = original.pathname;
      url.search = original.search;
    }
  }
  return url;
}

function routeMatches(pattern, pathname) {
  const patternParts = pattern.split('/').filter(Boolean);
  const pathParts = pathname.split('/').filter(Boolean);
  if (patternParts.at(-1) === '*') {
    if (pathParts.length < patternParts.length - 1) return false;
  } else if (patternParts.length !== pathParts.length) {
    return false;
  }
  return patternParts.every((part, index) => part === '*' || part.startsWith(':') || part === pathParts[index]);
}

function findRoute(pathname) {
  const apiPath = pathname.replace(/^\\/api(?=\\/$|\\/)/, '') || '/';
  return routePatterns.find(({ pattern }) => routeMatches(pattern, apiPath));
}

function webRequest(req, url) {
  const headers = new Headers();
  for (const [name, value] of Object.entries(req.headers || {})) {
    if (Array.isArray(value)) headers.set(name, value.join(', '));
    else if (value != null) headers.set(name, String(value));
  }
  const init = { method: req.method || 'GET', headers };
  if (init.method !== 'GET' && init.method !== 'HEAD') {
    init.body = req;
    init.duplex = 'half';
  }
  return new Request(url, init);
}

async function sendWebResponse(res, response) {
  res.statusCode = response.status;
  response.headers.forEach((value, key) => res.setHeader(key, value));
  if (!response.body) {
    res.end();
    return;
  }
  const reader = response.body.getReader();
  try {
    while (true) {
      const { done, value } = await reader.read();
      if (done) break;
      res.write(value);
    }
  } finally {
    res.end();
  }
}

export default async function handler(req, res) {
  const url = requestUrl(req);
  const route = findRoute(url.pathname);
  if (!route) {
    res.statusCode = 404;
    res.setHeader('Content-Type', 'application/json; charset=utf-8');
    res.end(JSON.stringify({ error: 'Route not found' }));
    return;
  }

  try {
    const module = await route.load();
    const routeHandler = module.default;
    if (typeof routeHandler !== 'function') throw new Error('Route has no default handler');

    if (nodeStyleRoutes.has(route.pattern)) {
      await routeHandler(req, res);
      return;
    }

    const response = await routeHandler(
      webRequest(req, url),
      { waitUntil: (promise) => Promise.resolve(promise).catch(() => {}) },
    );
    if (response instanceof Response) {
      await sendWebResponse(res, response);
    } else if (!res.writableEnded) {
      res.statusCode = 500;
      res.end(JSON.stringify({ error: 'Route did not return a Response' }));
    }
  } catch (error) {
    console.error('[Vercel API router]', error);
    if (!res.writableEnded) {
      res.statusCode = 500;
      res.setHeader('Content-Type', 'application/json; charset=utf-8');
      res.end(JSON.stringify({ error: 'Internal server error' }));
    }
  }
}
`;
}

// The single-function router must not resolve its staged route modules at
// runtime: Vercel ships the hidden staging dir (.vercel-api-routes/) loose to
// the lambda and leaves the generated dynamic import() calls intact, and Node
// ESM cannot import extensionless .js or .ts modules at runtime. Bundle the
// node router (api/index.ts) with esbuild at prepare time so the deployed
// router is one self-contained file.
//
// api/mcp.ts is deliberately NOT bundled. Vercel detects the Edge runtime from
// the literal `export const config = { runtime: 'edge' }` in the entry source;
// esbuild rewrites that pattern into `var config = ...; export { config }`,
// which Vercel's detector misses. The route then deploys as a Node.js
// Serverless Function, is invoked as (req, res) with an IncomingMessage (plain
// `headers` object, no .get), and crashes on the first req.headers.get() — 500
// on every MCP method including anonymous ping/initialize and GET discovery
// (observed as the Hermès integration failure on the fork). Keeping the source
// entry (imports already rewritten to ../.vercel-api-routes/mcp/ by
// rewriteMcpEntryImports) lets Vercel's own edge bundler resolve the staged
// tree at build time, exactly like upstream's api/mcp.ts -> ./mcp/* layout.
// Function count stays at exactly two (api/index.ts node + api/mcp.ts edge)
// because the hidden staging dir is never counted as functions.
function bundleGeneratedFunctions() {
  return (async () => {
    let build;
    try {
      build = (await import('esbuild')).build;
    } catch (error) {
      throw new Error(
        '[prepare-vercel] esbuild is required to bundle the single-function router; run npm ci first',
      );
    }
    await build({
      entryPoints: [generatedIndex],
      bundle: true,
      platform: 'node',
      format: 'esm',
      target: ['node20'],
      outfile: generatedIndex,
      allowOverwrite: true,
      logLevel: 'warning',
    });
    // esbuild preserves trailing whitespace and space-before-tab from embedded
    // sources (comments, Lua/SQL templates). The workflow's `git diff --check`
    // validation rejects both, so normalize the bundled output.
    cleanBundleWhitespace(generatedIndex);
    console.log('[prepare-vercel] bundled api/index.ts (node) into a self-contained function; api/mcp.ts stays a source edge entry');
  })();
}

// Strip trailing whitespace and space-before-tab indentation from a generated
// bundle so `git diff --check` stays green in the sync workflow. Only leading
// indentation and end-of-line whitespace are touched; bundled content is
// otherwise byte-identical, so semantics never change.
function cleanBundleWhitespace(file) {
  const source = readFileSync(file, 'utf8');
  const cleaned = source
    .split('\n')
    .map((line) => {
      // Fix "space before tab" inside the leading indentation first.
      const leading = line.match(/^[ \t]*/)[0];
      const fixedLeading = leading.replace(/ +\t/g, '\t');
      // Strip trailing whitespace from the full line so whitespace-only
      // lines (which live entirely in the leading match) are emptied too.
      return (fixedLeading + line.slice(leading.length)).replace(/[ \t]+$/, '');
    })
    .join('\n');
  if (cleaned !== source) writeFileSync(file, cleaned);
}

// Vercel discovers functions from api/ before the build command runs, so the
// route modules moved out of api/ are no longer reachable through the specific
// rewrites in vercel.json (e.g. /ask -> /api/ask). Point every /api/<route>
// rewrite destination at the single generated index.ts instead, carrying the
// route through __wm_route so requestUrl() can dispatch it. api/mcp.ts stays a
// real function, so /api/mcp keeps its direct destination.
function rewriteVercelDestinations() {
  const vercelPath = join(root, 'vercel.json');
  const raw = readFileSync(vercelPath, 'utf8');
  const rewritten = raw.replace(
    /("destination":\s*"\/api\/)([^"?]+)(\?[^"]*)?(")/g,
    (match, prefix, route, query, suffix) => {
      if (route === 'index') return match;
      if (route === 'mcp' && !query) return match;
      const queryPart = query ? `&${query.slice(1)}` : '';
      return `${prefix}index?__wm_route=${route}${queryPart}${suffix}`;
    },
  );
  if (rewritten !== raw) writeFileSync(vercelPath, rewritten);
}

