// The single-function branch keeps only api/index.ts (plus api/mcp.ts) as real
// Vercel Serverless Functions. Vercel maps a request to /api/<path> against an
// api/<path> file, and the consolidated branch no longer has those files (they
// moved into .vercel-api-routes/ so the free plan stays under the function
// limit). Without a catch-all rewrite, every direct frontend call to /api/
// — /api/wm-session, /api/bootstrap, /api/*/v1/*, /api/health — returns 404 and
// the dashboard renders empty. Add { source: '/api/(.*)', destination:
// '/api/index' } so the generated router receives the whole /api namespace and
// restores the original path from the x-matched-path header Vercel attaches to
// rewrite destinations. The destination intentionally carries NO query so
// Vercel keeps forwarding the caller's original query string, which the router
// re-applies alongside the restored path. api/mcp.ts stays a real function and
// takes route precedence, so /api/mcp is unaffected.
function ensureApiCatchAllRewrite() {
  const vercelPath = join(root, 'vercel.json');
  const raw = readFileSync(vercelPath, 'utf8');
  let obj;
  try {
    obj = JSON.parse(raw);
  } catch {
    throw new Error('[prepare-vercel] vercel.json is not valid JSON; cannot add the /api catch-all rewrite');
  }
  const rewrites = Array.isArray(obj.rewrites) ? obj.rewrites : [];
  // Exact string comparison: the canonical catch-all rewrite carries the literal
  // source '/api/(.*)' (the parens are data, not regex), routed to the router.
  const alreadyRouted = rewrites.some(
    (rewrite) =>
      rewrite &&
      rewrite.source === '/api/(.*)' &&
      typeof rewrite.destination === 'string' &&
      rewrite.destination.includes('/api/index'),
  );
  if (alreadyRouted) return;
  const marker = '"rewrites": [';
  if (!raw.includes(marker)) {
    throw new Error(
      '[prepare-vercel] vercel.json has no "rewrites" array; cannot add the /api catch-all rewrite',
    );
  }
  const insertion = '\n    { "source": "/api/(.*)", "destination": "/api/index" },';
  writeFileSync(vercelPath, raw.replace(marker, marker + insertion));
  console.log('[prepare-vercel] ensured /api/(.*) -> /api/index catch-all rewrite');
}

// docs-stats (used by inventory:facts in postinstall) reads api/bootstrap.js,
// api/health.js, and api/mcp/* files, all of which move into .vercel-api-routes/.
// Add a fallback in its read() helper so the moved reads resolve against the
// staged tree.
function patchDocsStatsReadFallback() {
  const docsStatsPath = join(root, 'scripts', 'docs-stats.mjs');
  const raw = readFileSync(docsStatsPath, 'utf8');
  const marker = "const read = (p) => readFileSync(join(rootOf(), p), 'utf8');";
  if (!raw.includes(marker)) return; // already patched, or upstream changed the helper
  const fallback = `const read = (p) => {
  const primary = join(rootOf(), p);
  try {
    return readFileSync(primary, 'utf8');
  } catch (error) {
    // Vercel single-function deploy branch: api/ route modules are staged into
    // .vercel-api-routes/ (same depth). Resolve api/* reads that moved there so
    // inventory:facts still works during postinstall.
    if (error?.code === 'ENOENT' && p.startsWith('api/')) {
      return readFileSync(join(rootOf(), '.vercel-api-routes', p.slice('api/'.length)), 'utf8');
    }
    throw error;
  }
};`;
  writeFileSync(docsStatsPath, raw.replace(marker, fallback));
}

// The repo's .gitignore ignores internal/ and skills/ directories anywhere in
// the tree (api/internal and api/skills are re-included explicitly). The staged
// route tree mirrors those directories at .vercel-api-routes/internal and
// .vercel-api-routes/skills, which would otherwise be ignored and left out of
// the deploy branch commit. Re-include them the same way upstream re-includes
// their api/ counterparts so the generated api/index.ts routes keep resolving.
// api/mcp.ts imports its implementation from ./mcp/handler, ./mcp/auth, etc.
// After the mcp/ tree moves into .vercel-api-routes/mcp/, rewrite those imports
// to point at the staged tree so the /mcp endpoint keeps working at runtime.
function rewriteMcpEntryImports() {
  const mcpTsPath = join(apiDir, 'mcp.ts');
  const raw = readFileSync(mcpTsPath, 'utf8');
  const rewritten = raw.replace(
    /(from\s+)(['"])\.\/mcp\//g,
    '$1$2../.vercel-api-routes/mcp/',
  );
  if (rewritten !== raw) writeFileSync(mcpTsPath, rewritten);
}

