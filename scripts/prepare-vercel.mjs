async function main() {
  if (!(await stat(apiDir).catch(() => null))) {
    throw new Error('api/ directory is missing; the canonical repository layout is required');
  }
  // --force regenerates an existing deployment branch in place: drop the
  // previous generated entry point and staging tree first so the transform is
  // idempotent (upstream itself ships an api/index.ts dynamic router that the
  // generated static import map must replace).
  if (await stat(generatedIndex).catch(() => null)) {
    if (!force) {
      throw new Error('api/index.ts already exists; remove the generated deployment artifact before preparing again (or use --force)');
    }
    await rm(generatedIndex, { force: true });
  }

  const files = await collectFiles(apiDir);
  const routes = sortRoutes(
    files
      .map((relativePath) => ({ relativePath, routePath: routePathFromFile(relativePath) }))
      .filter((entry) => entry.routePath),
  );

  if (check || !shouldPrepare()) {
    console.log(
      `[prepare-vercel] ${routes.length} route modules discovered; ` +
      (shouldPrepare() ? 'deployment transformation enabled' : 'repository unchanged (use VERCEL=1 or --force to stage)'),
    );
    return;
  }

  if (await stat(stagingDir).catch(() => null)) {
    if (!force) {
      throw new Error(`${relative(root, stagingDir)} already exists; refusing to overwrite a previous staging tree (or use --force)`);
    }
    await rm(stagingDir, { recursive: true, force: true });
  }

  // Stage the ENTIRE api/ tree (except test files) into .vercel-api-routes/ at
  // the same depth as api/, so relative imports keep resolving. Non-underscore
  // route files are removed from api/ so Vercel discovers only the generated
  // router and stays within the Hobby function limit.
  await mkdir(stagingDir, { recursive: true });

  for (const relativePath of files) {
    if (/\.(test|spec)\./.test(relativePath)) continue;
    const src = join(apiDir, relativePath);
    const dest = join(stagingDir, relativePath);
    const destDir = dirname(dest);
    await mkdir(destDir, { recursive: true });
    await cp(src, dest);
    if (!staysInApi(relativePath)) {
      await rm(src, { force: true });
    }
  }

  patchDocsStatsReadFallback();
  rewriteMcpEntryImports();
  patchProductFactsImport();
  allowStagedGitignoreExceptions();
  createEmptyMcpDir();
  forkUnlockProGates();
  forkVariantSwitchPatches();
  forkSourceAttributionScan();
  forkCorsAllowlistPatch();
  forkSessionRateLimitFailOpen();
  forkHealthDiagnostic();
  forkSitemapCorpusPatch();
  forkStructuredContentPatch();


  await writeFile(generatedIndex, renderIndex(routes));
  rewriteVercelDestinations();
  ensureApiCatchAllRewrite();
  rewriteBuildCommand();

  // Make both function entries self-contained so the deployed lambda never
  // resolves the staged route modules at runtime (see bundleGeneratedFunctions).
  await bundleGeneratedFunctions();

  const stagedCount = files.filter((relativePath) => !staysInApi(relativePath) && !/\.(test|spec)\./.test(relativePath)).length;
  console.log(
    `[prepare-vercel] staged ${stagedCount} api files (${routes.length} routes) behind api/index.ts`,
  );
}

await main();
